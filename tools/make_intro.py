#!/usr/bin/env python3
"""Turn a photo into demo/intro_img.c, the picture the game shows for three seconds before it starts.

    python3 tools/make_intro.py photo.jpg [demo/intro_img.c]

The photo is fitted into 180x240 (the height of the top screen), with the corners that don't fit cropped, then
reduced to 5-6-5 colour with error diffusion so the soft shading doesn't turn into bands. The game draws it
in the middle of the top screen on a plain background taken from the photo's average colour.
Needs Python 3 and Pillow.
"""
import sys
from PIL import Image, ImageOps

W, H = 180, 240
src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else "demo/intro_img.c"

img = ImageOps.exif_transpose(Image.open(src)).convert("RGB")
img = ImageOps.fit(img, (W, H), method=Image.LANCZOS, centering=(0.5, 0.5))

# average colour, darkened: the background around the picture
small = img.resize((1, 1), Image.BOX).getpixel((0, 0))
bg = tuple(int(c * 0.22) for c in small)

# Floyd-Steinberg to 5-6-5
px = [[list(img.getpixel((x, y))) for x in range(W)] for y in range(H)]
words = []
for y in range(H):
    for x in range(W):
        r, g, b = px[y][x]
        r = min(255, max(0, r)); g = min(255, max(0, g)); b = min(255, max(0, b))
        r5, g6, b5 = round(r * 31 / 255), round(g * 63 / 255), round(b * 31 / 255)
        words.append((r5 << 11) | (g6 << 5) | b5)
        er, eg, eb = r - r5 * 255 / 31, g - g6 * 255 / 63, b - b5 * 255 / 31
        for dx, dy, f in ((1, 0, 7 / 16), (-1, 1, 3 / 16), (0, 1, 5 / 16), (1, 1, 1 / 16)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < W and ny < H:
                p = px[ny][nx]
                p[0] += er * f; p[1] += eg * f; p[2] += eb * f

with open(out, "w") as f:
    f.write("/* Generated by tools/make_intro.py: the picture shown for three seconds before the game starts.\n")
    f.write(" * %dx%d, 5-6-5 colour (red in the top bits), row by row. Do not edit by hand. */\n" % (W, H))
    f.write('#include "intro_img.h"\n\n')
    f.write("const unsigned char g_intro_bg[3] = { %d, %d, %d };\n\n" % bg)
    f.write("const unsigned short g_intro_pix[INTRO_W * INTRO_H] = {\n")
    for i in range(0, len(words), 12):
        f.write("    " + ",".join("0x%04x" % w for w in words[i:i + 12]) + ",\n")
    f.write("};\n")
print("wrote %s: %dx%d, background rgb%s" % (out, W, H, bg))
